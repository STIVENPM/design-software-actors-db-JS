CREATE TABLE IF NOT EXISTS actors_companies.company (
    id UUID NOT NULL,
    nit VARCHAR(20) NOT NULL,
    business_name VARCHAR(200) NOT NULL,
    trade_name VARCHAR(200),
    economic_activity VARCHAR(100),
    address TEXT,
    city_id UUID,
    contact_name VARCHAR(200),
    contact_email VARCHAR(255),
    contact_phone VARCHAR(20),
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL,
    created_by UUID NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    updated_by UUID NOT NULL,
    deleted_at TIMESTAMPTZ,
    deleted_by UUID,
    row_version INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS actors_companies.productive_stage (
    id UUID NOT NULL,
    learner_id UUID NOT NULL,
    company_id UUID NOT NULL,
    supervisor_instructor_id UUID NOT NULL,
    start_date DATE NOT NULL,
    planned_end_date DATE NOT NULL,
    actual_end_date DATE,
    total_hours_required INT NOT NULL,
    total_hours_completed INT NOT NULL DEFAULT 0,
    status_id UUID NOT NULL,
    interruption_reason TEXT,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL,
    created_by UUID NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    updated_by UUID NOT NULL,
    deleted_at TIMESTAMPTZ,
    deleted_by UUID,
    row_version INT NOT NULL DEFAULT 0,
    CONSTRAINT ck_productive_stage_total_hours_required CHECK (total_hours_required >= 0),
    CONSTRAINT ck_productive_stage_total_hours_completed CHECK (total_hours_completed >= 0),
    CONSTRAINT ck_productive_stage_planned_dates CHECK (planned_end_date >= start_date),
    CONSTRAINT ck_productive_stage_actual_dates CHECK (actual_end_date IS NULL OR actual_end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS actors_companies.company_visit (
    id UUID NOT NULL,
    productive_stage_id UUID NOT NULL,
    instructor_id UUID NOT NULL,
    visit_number SMALLINT NOT NULL,
    visit_date DATE NOT NULL,
    visit_type VARCHAR(10) NOT NULL,
    learner_performance VARCHAR(12) NOT NULL,
    company_satisfaction VARCHAR(6),
    observations TEXT,
    next_visit_date DATE,
    has_improvement_plan BOOLEAN NOT NULL DEFAULT false,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL,
    created_by UUID NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    updated_by UUID NOT NULL,
    deleted_at TIMESTAMPTZ,
    deleted_by UUID,
    row_version INT NOT NULL DEFAULT 0,
    CONSTRAINT ck_company_visit_visit_number CHECK (visit_number > 0),
    CONSTRAINT ck_company_visit_visit_type CHECK (visit_type IN ('IN_PERSON','VIRTUAL','PHONE')),
    CONSTRAINT ck_company_visit_learner_performance CHECK (learner_performance IN ('EXCELLENT','GOOD','ACCEPTABLE','DEFICIENT')),
    CONSTRAINT ck_company_visit_company_satisfaction CHECK (company_satisfaction IS NULL OR company_satisfaction IN ('HIGH','MEDIUM','LOW'))
);
